import React, { useState } from 'react';
import { HelpCircle, CheckCircle2, AlertCircle } from 'lucide-react';

export interface UtrInputProps {
  value: string;
  onChange: (val: string) => void;
  error?: string;
  disabled?: boolean;
}

export function UtrInput({ value, onChange, error, disabled }: UtrInputProps) {
  const [showTooltip, setShowTooltip] = useState(false);

  const cleanValue = value.replace(/[^a-zA-Z0-9]/g, '').toUpperCase();

  const handleInputChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const raw = e.target.value;
    const sanitized = raw.replace(/[^a-zA-Z0-9]/g, '').toUpperCase();
    onChange(sanitized);
  };

  const getFeedback = () => {
    if (!cleanValue) {
      return {
        text: 'Enter the 12-digit UTR/Reference number from your UPI app receipt',
        color: 'text-gray-400',
      };
    }
    if (cleanValue.length < 10) {
      return {
        text: `UTR must be at least 10 characters (${cleanValue.length}/12 entered)`,
        color: 'text-amber-400',
      };
    }
    return {
      text: '✅ Looks good',
      color: 'text-emerald-400 font-semibold',
    };
  };

  const feedback = getFeedback();

  return (
    <div className="space-y-1.5">
      <div className="flex items-center justify-between">
        <label className="text-xs font-semibold text-gray-300 uppercase tracking-wider block">
          12-Digit UPI Ref / UTR Number
        </label>
        <div className="relative">
          <button
            type="button"
            onClick={() => setShowTooltip(!showTooltip)}
            onMouseEnter={() => setShowTooltip(true)}
            onMouseLeave={() => setShowTooltip(false)}
            className="text-gray-400 hover:text-white flex items-center gap-1 text-[11px] cursor-pointer"
          >
            <HelpCircle className="w-3.5 h-3.5 text-orange-400" />
            <span>Where is UTR?</span>
          </button>

          {showTooltip && (
            <div className="absolute right-0 bottom-full mb-2 w-64 p-3 rounded-xl bg-slate-900 border border-white/20 shadow-2xl z-50 text-[11px] text-gray-300 leading-relaxed animate-in fade-in">
              <span className="font-bold text-white block mb-1">About UTR (Transaction ID)</span>
              The UTR (Unique Transaction Reference) is a 12-digit numeric reference generated by your UPI bank. In Google Pay, PhonePe, or Paytm, tap the completed transaction and find <strong>"UPI Ref No"</strong> or <strong>"Transaction ID"</strong>.
            </div>
          )}
        </div>
      </div>

      <div className="relative">
        <input
          type="text"
          value={cleanValue}
          onChange={handleInputChange}
          maxLength={16}
          disabled={disabled}
          placeholder="e.g. 425348648634"
          className="w-full px-3.5 py-2.5 rounded-xl text-sm font-mono tracking-widest text-white bg-white/5 border border-white/10 placeholder-gray-500 outline-none focus:border-orange-500 focus:bg-white/[0.08] transition-all"
        />
        {cleanValue.length >= 10 && (
          <CheckCircle2 className="w-4 h-4 text-emerald-400 absolute right-3.5 top-1/2 -translate-y-1/2 pointer-events-none" />
        )}
      </div>

      {error ? (
        <p className="text-xs text-rose-400 flex items-center gap-1 mt-1">
          <AlertCircle className="w-3.5 h-3.5 shrink-0" />
          <span>{error}</span>
        </p>
      ) : (
        <p className={`text-[11px] mt-1 ${feedback.color}`}>
          {feedback.text}
        </p>
      )}
    </div>
  );
}
